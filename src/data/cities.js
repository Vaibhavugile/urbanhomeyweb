/* =========================================================
   SLUG GENERATOR
========================================================= */

export function createCitySlug(value = "") {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
    .replace(/&/g, "and")
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}


/* =========================================================
   CREATE LOCATION OBJECT
========================================================= */

function createLocationEntry({
  name,
  parentCity,
  state,
}) {
  const slug = createCitySlug(name);

  return {
    slug,

    name,

    state,

    /*
     * Used internally so we know which
     * main city this location belongs to.
     */

    parentCity,


    /* =========================
       SEO
    ========================= */

    title:
      `Find Flatmates, Roommates & Rooms for Rent in ${name} | UrbanHomey`,

    description:
      `Find compatible flatmates, roommates, shared rooms and rooms for rent in ${name}. Explore shared accommodation and connect with compatible people based on budget, lifestyle and living preferences with UrbanHomey.`,

    keywords:
      `flatmates in ${name}, roommates in ${name}, find flatmate ${name}, find roommate ${name}, rooms for rent in ${name}, shared rooms in ${name}, shared accommodation ${name}, roommate finder ${name}, flatmate finder ${name}, verified flatmates ${name}, student rooms ${name}, rooms for working professionals ${name}, co living ${name}, UrbanHomey ${name}`,

    heading:
      `Find Flatmates, Roommates & Rooms in ${name}`,

    shortDescription:
      `Discover compatible flatmates, roommates, rooms for rent and shared accommodation in ${name} based on location, budget, lifestyle and living preferences.`,


    /*
     * Generated locations currently
     * don't contain child locations.
     */

    areas: [],


    /*
     * Helpful for CityPage,
     * sitemap and filtering.
     */

    isGeneratedLocation: true,
  };
}


/* =========================================================
   MAIN CITIES WHOSE AREAS SHOULD BECOME
   TOP-LEVEL SEO LOCATION PAGES
========================================================= */

const LOCATION_GENERATION_CONFIG = [
  {
    citySlug: "pune",
  },

  {
    citySlug: "mumbai",
  },
];


/* =========================================================
   GENERATE LOCATION ENTRIES
========================================================= */

LOCATION_GENERATION_CONFIG.forEach(
  ({ citySlug }) => {

    const parentCity = cities[citySlug];


    /*
     * Safety check.
     */

    if (!parentCity) {
      console.warn(
        `[cities.js] Cannot generate locations. City "${citySlug}" does not exist.`
      );

      return;
    }


    /*
     * Safety check for areas.
     */

    if (!Array.isArray(parentCity.areas)) {
      return;
    }


    parentCity.areas.forEach((areaName) => {

      const location =
        createLocationEntry({
          name: areaName,

          parentCity: parentCity.slug,

          state: parentCity.state,
        });


      /*
       * Never overwrite an existing manually
       * created city/location.
       *
       * Example:
       *
       * If "pimpri" already exists manually,
       * automatic generation will skip it.
       */

      if (cities[location.slug]) {
        return;
      }


      cities[location.slug] = location;

    });

  }
);


